import os
import re
import unittest
import uuid
from unittest.mock import patch

import psycopg2
from psycopg2 import sql
from psycopg2.extensions import parse_dsn

from app.config import DATABASE_URL
from app.tools import agenda, financeiro
from app import execucao


class BancoIsolado(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        cls.dsn = os.getenv("TEST_DATABASE_URL") or DATABASE_URL
        if not cls.dsn:
            raise unittest.SkipTest("Configure TEST_DATABASE_URL ou DATABASE_URL para testes SQL isolados.")
        cls.schema = "test_juiz_" + uuid.uuid4().hex
        cls.admin = psycopg2.connect(cls.dsn)
        cls.admin.autocommit = True
        with cls.admin.cursor() as cur:
            cur.execute(sql.SQL("CREATE SCHEMA {}").format(sql.Identifier(cls.schema)))
        conn = cls.conectar()
        try:
            with conn.cursor() as cur:
                cur.execute("""CREATE TABLE transaction_types(id integer PRIMARY KEY,type text NOT NULL);
                    CREATE TABLE categories(id integer PRIMARY KEY,name text NOT NULL);
                    INSERT INTO transaction_types VALUES (1,'INCOME'),(2,'EXPENSES'),(3,'TRANSFER');
                    INSERT INTO categories VALUES (1,'outros'),(2,'besteira');
                    CREATE TABLE transactions(
                        id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        amount numeric(14,2) NOT NULL CHECK(amount<>999),
                        type integer NOT NULL REFERENCES transaction_types,
                        category_id integer REFERENCES categories,description text,payment_method varchar,
                        occurred_at timestamptz NOT NULL,source_text text NOT NULL);
                    CREATE TABLE events(id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        title text NOT NULL,start_time timestamptz NOT NULL,end_time timestamptz,
                        location text,notes text,recorded_at timestamptz NOT NULL DEFAULT now(),source_text text NOT NULL);""")
            conn.commit()
        finally:
            conn.close()

    @classmethod
    def conectar(cls):
        opcoes = parse_dsn(cls.dsn).get("options", "")
        return psycopg2.connect(cls.dsn, options=f"{opcoes} -c timezone=America/Sao_Paulo -c search_path={cls.schema}")

    @classmethod
    def tearDownClass(cls):
        if not re.fullmatch(r"test_juiz_[a-f0-9]{32}", cls.schema):
            raise RuntimeError("Nome do schema de teste inválido; limpeza cancelada.")
        try:
            with cls.admin.cursor() as cur:
                cur.execute(sql.SQL("DROP SCHEMA {} CASCADE").format(sql.Identifier(cls.schema)))
        finally:
            cls.admin.close()

    def setUp(self):
        for modulo in (financeiro, agenda, execucao):
            remendo = patch.object(modulo, "get_conn", self.conectar)
            remendo.start()
            self.addCleanup(remendo.stop)
        self.sql("TRUNCATE transactions,events RESTART IDENTITY")

    def sql(self, texto, parametros=()):
        conn = self.conectar()
        try:
            with conn.cursor() as cur:
                cur.execute(texto, parametros)
                resultado = cur.fetchall() if cur.description else None
            conn.commit()
            return resultado
        finally:
            conn.close()
